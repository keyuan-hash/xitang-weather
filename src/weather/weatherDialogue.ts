export function dialogueOptions(
  scene: SceneId,
  current: Pick<CurrentWeather, 'temperature' | 'time'>,
) {
  const options = [...weatherDialogues[scene]];
  if (
    current.temperature != null &&
    current.temperature <= 5 &&
    !['thunderstorm', 'heavy-rain'].includes(scene)
  )
    options.push(...coldDialogues);
  const hour = Number(current.time.slice(11, 13));
  if (scene === 'sunny' && hour >= 5 && hour < 10) options.push(...morningDialogues);
  return options;
}
export function getDialogue(
  scene: SceneId,
  current: Pick<CurrentWeather, 'temperature' | 'time'>,
  random = Math.random,
  exclude: string[] = [],
) {
  const all = dialogueOptions(scene, current);
  const fresh = all.filter((line) => !exclude.includes(line));
  const options = fresh.length ? fresh : all;
  return options[Math.min(options.length - 1, Math.max(0, Math.floor(random() * options.length)))];
}
export const dialogueCount =
  Object.values(weatherDialogues).reduce((total, lines) => total + lines.length, 0) +
  coldDialogues.length +
  morningDialogues.length;
